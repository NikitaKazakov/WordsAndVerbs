def cell_text(cell: str) -> str:
    return "".join(re.findall(r"<w:t[^>]*>([^<]*)</w:t>", cell)).replace("\xa0", " ").strip()


def normalize_v1(v1: str) -> str:
    if v1 == "do/does":
        return "do"
    return v1


def normalize_v2(v1: str, v2: str) -> str:
    if v1 == "be":
        return "was/were"
    return re.sub(r"\s*;\s*", "/", v2)


def main() -> None:
    with zipfile.ZipFile(DOCX) as zf:
        xml = zf.read("word/document.xml").decode("utf-8")
    rows = re.findall(r"<w:tr[\s>][\s\S]*?</w:tr>", xml)
    verbs = []
    missing = []
    for row in rows[1:]:
        cells = [cell_text(c) for c in re.findall(r"<w:tc[\s>][\s\S]*?</w:tc>", row)]
        if len(cells) < 4:
            continue
        raw_v1 = cells[1]
        v1 = normalize_v1(raw_v1)
        v2 = normalize_v2(v1, cells[2])
        v3 = cells[3]
        ru = RU.get(raw_v1) or RU.get(v1)
        if not ru:
            missing.append(raw_v1)
            ru = raw_v1
        verbs.append({"id": v1, "ru": ru, "v1": v1, "v2": v2, "v3": v3})
    if missing:
        raise SystemExit(f"Missing translations: {missing}")
    ids = [v["id"] for v in verbs]
    if len(ids) != len(set(ids)):
        raise SystemExit("Duplicate ids")
    if len(verbs) != 277:
        raise SystemExit(f"Expected 277 verbs, got {len(verbs)}")
    out = ROOT / "verbs.json"
    out.write_text(json.dumps(verbs, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(verbs)} verbs -> {out}")


if __name__ == "__main__":
    main()
